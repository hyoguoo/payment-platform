@RequiredArgsConstructor
public enum EventType {

    PG_CONFIRM_RECEIVED,
    /** inbox 진입 상태가 PENDING 으로 시작됨을 나타낸다. */
    PG_CONFIRM_PENDING_INSERT,
    PG_CONFIRM_IN_PROGRESS_NOOP,
    PG_CONFIRM_IN_PROGRESS_RETRY,
    PG_CONFIRM_TERMINAL_REEMIT,
    PG_CONFIRM_IN_PROGRESS_PREEMPTED,
    PG_CONFIRM_VENDOR_DELEGATED,

    PG_VENDOR_SUCCESS,
    /** transitToApproved 가드(이미 종결)에 걸려 승인 발행 행 저장 + 이벤트 발행을 하지 않은 경우. */
    PG_VENDOR_SUCCESS_GUARD_BLOCKED,
    PG_VENDOR_RETRY_SCHEDULED,
    /** incrementAttempt 가드(종결 행)에 걸려 재시도 outbox INSERT + 발행을 하지 않은 경우. */
    PG_VENDOR_RETRY_GUARD_BLOCKED,
    PG_VENDOR_DLQ,
    PG_VENDOR_DEFINITIVE_FAILURE,
    /** transitToFailed 가드(이미 종결)에 걸려 실패 발행 행 저장 + 이벤트 발행을 하지 않은 경우. */
    PG_VENDOR_DEFINITIVE_FAILURE_GUARD_BLOCKED,
    PG_VENDOR_DUPLICATE_HANDLED,
    PG_VENDOR_NETWORK_ERROR,
    PG_VENDOR_RETRYABLE_ERROR,
    PG_VENDOR_NON_RETRYABLE_ERROR,
    PG_VENDOR_PARSE_ERROR,
    /** 같은 멱등키로 아직 처리 중인 원 호출과 겹쳐 벤더가 거부한 경우 — 원 호출이 결과를 낼 예정이라 물러난다. */
    PG_VENDOR_CONCURRENT_CALL,

    PG_FCG_INDETERMINATE,
    PG_FCG_AMBIGUOUS_STATUS,
    PG_FCG_APPROVED,
    PG_FCG_FAILED,
    PG_FCG_QUARANTINED,

    /** 관리자 벤더 상태 조회 — 조회 과정의 예외(게이트웨이 예외·미처리 주문 예외 등)를 확인불가로 접은 경우. */
    PG_VENDOR_STATUS_QUERY_INDETERMINATE,

    PG_DLQ_NO_INBOX,
    PG_DLQ_ALREADY_TERMINAL,
    PG_DLQ_PREEMPTED,
    PG_DLQ_QUARANTINED,

    PG_DUPLICATE_EVENT_RECEIVED,
    PG_DUPLICATE_VENDOR_INDETERMINATE,
    PG_DUPLICATE_AMOUNT_MISMATCH_DB_EXISTS,
    PG_DUPLICATE_REEMIT,
    PG_DUPLICATE_REEMIT_DONE,
    PG_DUPLICATE_AMOUNT_MISMATCH_QUARANTINED_DB_EXISTS,
    /** transitToQuarantined 가드(경합으로 이미 종결)에 걸려 격리 발행 행 저장을 하지 않은 경우. */
    PG_DUPLICATE_AMOUNT_MISMATCH_GUARD_BLOCKED,
    PG_DUPLICATE_DB_ABSENT_APPROVED,
    PG_DUPLICATE_DB_ABSENT_APPROVED_DONE,
    PG_DUPLICATE_AMOUNT_MISMATCH_QUARANTINED_DB_ABSENT,
    PG_DUPLICATE_QUARANTINED_VENDOR_INDETERMINATE,
    /** 종결 전 기록 + 금액 일치 + 벤더 상태가 승인이 아닌 경우 — 종결시키지 않고 물러난다. */
    PG_DUPLICATE_UNSETTLED_STATUS_NOT_APPROVED,
    /** 종결 전 기록을 벤더 조회 결과로 승인 종결시킨 경우. */
    PG_DUPLICATE_UNSETTLED_SETTLED,
    /** transitToApproved 가드(경합으로 이미 종결)에 걸려 발행 행 저장을 하지 않은 경우. */
    PG_DUPLICATE_UNSETTLED_SETTLE_GUARD_BLOCKED,
    /** 종결 전 기록에 대한 벤더 상태 조회가 실패해 격리하지 않고 물러난 경우. */
    PG_DUPLICATE_UNSETTLED_INDETERMINATE_BACKOFF,
    /** transitToQuarantined 가드(경합으로 이미 종결)에 걸려 벤더 조회 실패 경로의 격리 발행 행 저장을 하지 않은 경우. */
    PG_DUPLICATE_INDETERMINATE_GUARD_BLOCKED,

    /** PENDING 상태에서 다른 워커에 선점된 경우. */
    PG_INBOX_AMOUNT_PENDING_PREEMPTED,
    PG_INBOX_AMOUNT_RECORDED,
    PG_INBOX_AMOUNT_NULL_QUARANTINED,
    PG_INBOX_AMOUNT_MISMATCH_QUARANTINED,
    PG_INBOX_AMOUNT_APPROVED,
    PG_INBOX_AMOUNT_DIRECT_APPROVED,

    PG_INBOX_WORKER_START,
    PG_INBOX_WORKER_SKIP,
    PG_INBOX_WORKER_PROCESS_FAIL,

    // ImmediateWorker SmartLifecycle 이벤트
    PG_INBOX_WORKER_STARTED,
    PG_INBOX_WORKER_STOPPED,
    PG_INBOX_WORKER_LOOP_ERROR,
    // 워커 처리 실패 카운터의 단일 출처
    PG_INBOX_WORKER_FAIL,

    PG_INBOX_CHANNEL_OVERFLOW,

    // InboxPollingWorker 좀비 회수 이벤트
    PG_INBOX_POLLING_PENDING_FOUND,
    PG_INBOX_POLLING_IN_PROGRESS_FOUND,
    PG_INBOX_POLLING_ZOMBIE_FAIL,

    // listener TX timeout + 좀비 회수 성공 이벤트
    PG_INBOX_LISTENER_TX_TIMEOUT,
    PG_INBOX_ZOMBIE_RECOVERED_PENDING,
    PG_INBOX_ZOMBIE_RECOVERED_IN_PROGRESS,

    PG_OUTBOX_CHANNEL_OVERFLOW,
    PG_OUTBOX_RELAY_NOT_FOUND,
    PG_OUTBOX_RELAY_ALREADY_PROCESSED,
    PG_OUTBOX_RELAY_NOT_AVAILABLE_YET,
    PG_OUTBOX_RELAY_DONE,
    PG_OUTBOX_WORKER_STARTED,
    PG_OUTBOX_WORKER_STOPPED,
    PG_OUTBOX_WORKER_LOOP_ERROR,
    PG_OUTBOX_WORKER_RELAY_FAIL,
    PG_OUTBOX_POLLING_PENDING_FOUND,
    PG_OUTBOX_POLLING_RELAY_FAIL,

    EXCEPTION,

    METRICS_INIT,
    METRICS_GAUGE_UPDATED,
}
