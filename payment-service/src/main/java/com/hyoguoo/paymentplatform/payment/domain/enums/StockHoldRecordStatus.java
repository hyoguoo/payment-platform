package com.hyoguoo.paymentplatform.payment.domain.enums;

/**
 * 재고 선차감 기록(상품 단위)의 상태.
 *
 * <p>되돌림과 확정을 하나로 묶지 않는다 — 되돌린 건과 실제 팔린 건을 구분하지 못하면
 * 회수 판정(잡음으로 남은 종결 건만 되돌린다)과 정합 확인이 흐려진다.
 */
public enum StockHoldRecordStatus {

    /**
     * 차감 직전에 적히는 상태. 아직 되돌려지지도 확정되지도 않았다.
     */
    NOISE,

    /**
     * 되돌리기로 닫힌 상태 — 거절 전용 되돌리기, 확정 실패, 격리 진입, 관리자 종결,
     * 주기 회수 중 하나가 재고를 복원하고 이 상태로 남긴다.
     */
    REVERTED,

    /**
     * 벤더 승인 반영과 같은 트랜잭션에서 확정된 상태. 이후 재요청에 훼손되지 않고
     * 캐시 차감 호출 자체도 건너뛴다.
     */
    COMMITTED
}
